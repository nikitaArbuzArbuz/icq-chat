import { useCallback, useEffect, useRef, useState } from 'react';

// Анимации изменений устроены одинаково: элемент, который показывает значение (бейдж, галочки,
// точка «в сети»), получает key от этого значения. Значение поменялось — React создаёт элемент заново,
// и CSS-анимация проигрывается. Два хука ниже не дают ей сработать там, где ничего не менялось.

/**
 * false при первой отрисовке компонента и true при всех следующих.
 * Когда список появляется на экране, счётчики и галочки не должны подпрыгивать все разом.
 */
export function useMounted() {
  const mounted = useRef(false);
  useEffect(() => {
    mounted.current = true;
  }, []);
  return mounted.current;
}

/**
 * Флаг разовой анимации: [играть ли, функция для onAnimationEnd].
 * Значение берётся при появлении элемента и потом не меняется: если бы класс с анимацией добавлялся
 * к уже показанному элементу при следующей перерисовке, анимация запустилась бы без всякого изменения.
 * Когда анимация закончилась, класс снимается: браузер заново проигрывает CSS-анимацию элемента,
 * который React переставил в списке, например при пересортировке контактов.
 */
export function useOneShot(animate) {
  const [play, setPlay] = useState(animate);
  const stop = useCallback(() => setPlay(false), []);
  return [play, stop];
}
